//
// Den europæiske rod: to mænd, der aldrig mødtes (der ligger omkring
// fem og et halvt århundrede mellem dem) og som tilsammen bestemte,
// hvordan man i Europa i to tusind år tænkte om sygdom. Den ene satsede
// på observation og indrømmede, at han vidste lidt; den anden byggede
// et lukket system, der besvarede ethvert spørgsmål — og netop derfor
// så længe ikke længere blev sat spørgsmålstegn ved.
//
// Dette kapitel gør, hvad forfatteren af denne bog har forlangt: Det
// analyserer TÆNKEMÅDEN grundigt — ikke kun, HVAD der blev gjort, men

// livsstilen som medicin og eden som et fags første selvforpligtelse —
// dertil den ærlige virkningsbalance: hvad der stadig står i dag
// (observation, etik, diætetik, nogle kirurgiske greb) og hvad der i
// århundreder har skadet (åreladning og afføringsmidler, som netop
// fulgte af denne teori).

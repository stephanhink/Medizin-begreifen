// Stimme des Vaidya — verfasste Opus. Die ZWEITE (der Blick von außen: die
// koloniale Verdrängung und die moderne Wiederentdeckung) und die finale
// Synthese ergänzte Hermes im zweiten Pass. Perspektiven-Workflow: CLAUDE.md.
//
// KEINE WIEDERHOLUNGEN (Betreiber-Entscheid vom 21.08.2026): Kapitel 1

// Kapitel 3 — „Indien und der Ayurveda".
//
// Die indische Heilkunde ist die zweite große Tradition, die ohne Bruch bis
// heute praktiziert wird — in Indien staatlich anerkannt, an eigenen
// Hochschulen gelehrt und weltweit verbreitet. Dieses Kapitel tut, was der
// Betreiber verlangt hat: Es analysiert ihre DENKART umfangreich — nicht
// nur, WAS getan wurde, sondern WARUM. Das Weltbild (die fünf Elemente, die
// drei Doshas Vata, Pitta und Kapha, Agni und Ama), die Begründungslogik
// hinter Ernährung, Diagnose, Kräutern, Panchakarma und Tagesordnung — und
// die ehrliche Wirkungsbilanz: was die Forschung heute stützt und was nicht
// messbar oder umstritten ist (CLAUDE.md, Denkart-Analyse).
//

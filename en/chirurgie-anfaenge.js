// Chapter 11 — "The Cruel Beginnings of Modern Surgery".
//
// The first chapter of the modern era. Here begins the medicine we know
// today — and it begins in a room where a fully conscious human being
// lies on a wooden table, held down by four men, while students stand
// watching from the galleries above. Modern medicine is barely a hundred
// and fifty years old, and its first decades were exactly as this chapter
// describes them.
//
// The WAY-OF-THINKING analysis is the heart of the chapter (operator
// requirement). Here it asks: Why did a surgeon have to be so fast?
// (Because there was no anaesthesia and the pain itself could kill —
// speed was the only mercy.) Why anatomy? (Because under the knife there
// is no time to look up where the artery runs — whoever does not know the
// dead body may not open the living one.) Why in public? (Because there
// was no other way to learn — and because fame was part of it.) Why the
// bought corpses? (Because the only legal source, the executed, did not
// cover the demand — and so a market arose.) And the blind spot of the
// whole way of thinking: nobody asked why the wound suppurated later.
//
// LENGTH RULE (operator feedback, 24.08.2026): From the modern era the
// rule is reversed — this chapter is told IN DETAIL and vividly ("the
